BitmapFont::BitmapFont() = default;

void BitmapFont::SetGlyphs(std::vector<Glyph> glyphs, const int atlas_id, const int atlas_w, const int atlas_h) {
	glyphs_ = std::move(glyphs);
	atlas_id_ = atlas_id;
	atlas_w_ = atlas_w;
	atlas_h_ = atlas_h;
	embedded_ = false;
}

const Glyph* BitmapFont::Find(const int code) const {
	for (const Glyph& g : glyphs_) {
		if (g.code == code) {
			return &g;
		}
	}
	return nullptr;
}

int BitmapFont::Measure(const char* text, const float scale) const {
	if (text == nullptr) {
		return 0;
	}
	int w = 0;
	for (const char* p = text; *p != '\0'; ++p) {
		if (!embedded_) {
			const Glyph* g = Find(static_cast<int>(*p));
			w += g != nullptr ? g->advance : 8;
		} else {
			w += 8;
		}
	}
	return static_cast<int>(static_cast<float>(w) * scale);
}

void BitmapFont::Draw(
	Engine& engine,
	const char* text,
	const int x,
	const int y,
	const std::uint32_t packed_color,
	const float scale,
	const TextAlign align) const {
	if (text == nullptr) {
		return;
	}
	const int width = Measure(text, scale);
	int cx = x;
	if (align == TextAlign::Center) {
		cx -= width / 2;
	} else if (align == TextAlign::Right) {
		cx -= width;
	}
	const int cell = std::max(1, static_cast<int>(scale));
	for (const char* p = text; *p != '\0'; ++p) {
		if (!embedded_) {
			const Glyph* g = Find(static_cast<int>(*p));
			if (g != nullptr && atlas_id_ >= 0) {
				engine.DrawSprite(atlas_id_, g->x, g->y, g->w, g->h, cx, y);
				cx += static_cast<int>(static_cast<float>(g->advance) * scale);
			}
			continue;
		}
		const int gi = GlyphIndex(*p);
		for (int row = 0; row < 8; ++row) {
			const std::uint8_t bits = kGlyphs[gi][row];
			for (int col = 0; col < 8; ++col) {
				if ((bits & (0x80U >> col)) == 0U) {
					continue;
				}
				engine.PushCommand(MakeDrawCommand(
					CommandType::kRectFill,
					cx + col * cell,
					y + row * cell,
					cell,
					cell,
					packed_color));
			}
		}
		cx += 8 * cell;
	}
}

